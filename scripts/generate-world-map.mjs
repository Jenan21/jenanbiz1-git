#!/usr/bin/env node
// Generates the static world-map assets used by the pre-login globe from the @svg-maps/world package:
//   public/assets/gateway-world.v1.svg  one <path id="xx"> per country, fetched once and cached by the browser
//   components/auth/world-map-data.ts   country ids, names and label anchors, so the page never ships the outlines
// The outlines are about 1.2 MB. Inlining them put that weight into every pre-login page and its script bundle;
// referencing them with <use> renders exactly the same shapes while the page itself stays small.
//
//   npm run generate:world-map        rewrite the files
//   npm run generate:world-map -- --check   fail if the committed files are out of date
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { svgPathBbox } from "svg-path-bbox";

const require = createRequire(import.meta.url);
const world = require("@svg-maps/world");
const source = world.default ?? world;

const svgPath = fileURLToPath(new URL("../public/assets/gateway-world.v1.svg", import.meta.url));
const dataPath = fileURLToPath(new URL("../components/auth/world-map-data.ts", import.meta.url));

const escapeAttribute = (value) => value.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");

const svg = [
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${source.viewBox}">`,
  ...source.locations.map((location) => `<path id="${escapeAttribute(location.id)}" d="${escapeAttribute(location.path)}"/>`),
  "</svg>",
  "",
].join("\n");

const rows = source.locations.map((location) => {
  const [minX, minY, maxX, maxY] = svgPathBbox(location.path);
  return `  [${JSON.stringify(location.id)}, ${JSON.stringify(location.name)}, ${(minX + maxX) / 2}, ${(minY + maxY) / 2}],`;
});
const data = [
  "// Generated by scripts/generate-world-map.mjs from @svg-maps/world. Do not edit by hand.",
  `export const WORLD_VIEWBOX = ${JSON.stringify(source.viewBox)};`,
  "",
  "/** The asset that holds every country outline, one `<path id>` per country. */",
  'export const WORLD_OUTLINES_URL = "/assets/gateway-world.v1.svg";',
  "",
  "/** [id, name, label anchor x, label anchor y] for every country, in drawing order. */",
  "export const WORLD_COUNTRIES: ReadonlyArray<readonly [id: string, name: string, x: number, y: number]> = [",
  ...rows,
  "];",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const stale = [];
  const normalize = (text) => text.replace(/\r\n/g, "\n");
  if (normalize(readFileSync(svgPath, "utf8")) !== svg) stale.push("public/assets/gateway-world.v1.svg");
  if (normalize(readFileSync(dataPath, "utf8")) !== data) stale.push("components/auth/world-map-data.ts");
  if (stale.length) {
    console.error(`Out of date: ${stale.join(", ")}. Run npm run generate:world-map.`);
    process.exit(1);
  }
  console.log(`World-map assets are up to date (${source.locations.length} countries).`);
} else {
  writeFileSync(svgPath, svg, "utf8");
  writeFileSync(dataPath, data, "utf8");
  console.log(`Wrote ${source.locations.length} countries: ${(svg.length / 1024).toFixed(0)} KB outlines, ${(data.length / 1024).toFixed(1)} KB data.`);
}
