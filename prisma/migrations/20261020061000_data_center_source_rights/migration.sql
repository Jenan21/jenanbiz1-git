-- Data Center source rights: ownership, declared license class, usage policy, source URL and attribution.
-- Ownership (who owns the data), license (free text) and license class (declared usage posture) stay separate fields.
CREATE TYPE "DataCenterOwnership" AS ENUM ('PLATFORM_OWNED', 'USER_OWNED', 'THIRD_PARTY', 'AI_GENERATED');
CREATE TYPE "DataCenterLicenseClass" AS ENUM ('JENAN_OWNED', 'OPEN_LICENSE', 'LICENSED', 'RESTRICTED');

-- THIRD_PARTY and the restrictive usage policy are conservative defaults, not verified claims about existing sources.
ALTER TABLE "DataCenterSource"
  ADD COLUMN "sourceUrl" TEXT,
  ADD COLUMN "ownership" "DataCenterOwnership" NOT NULL DEFAULT 'THIRD_PARTY',
  ADD COLUMN "licenseClass" "DataCenterLicenseClass",
  ADD COLUMN "usagePolicy" TEXT NOT NULL DEFAULT 'Internal use; redistribution requires explicit permission',
  ADD COLUMN "attribution" TEXT,
  ADD COLUMN "attributionRequired" BOOLEAN NOT NULL DEFAULT false;

-- Generated sources are AI-generated by definition (the service already forces AI origin for them).
UPDATE "DataCenterSource" SET "ownership" = 'AI_GENERATED' WHERE "kind" = 'GENERATED';

ALTER TABLE "DataCenterSource"
  ADD CONSTRAINT "DataCenterSource_ownership_kind_check" CHECK (("kind" = 'GENERATED') = ("ownership" = 'AI_GENERATED')),
  ADD CONSTRAINT "DataCenterSource_usagePolicy_check" CHECK (length(btrim("usagePolicy")) BETWEEN 1 AND 2000),
  ADD CONSTRAINT "DataCenterSource_attribution_check" CHECK ("attribution" IS NULL OR length(btrim("attribution")) BETWEEN 1 AND 1000),
  ADD CONSTRAINT "DataCenterSource_attribution_required_check" CHECK (NOT "attributionRequired" OR "attribution" IS NOT NULL),
  ADD CONSTRAINT "DataCenterSource_sourceUrl_check" CHECK ("sourceUrl" IS NULL OR ("sourceUrl" ~ '^https?://[^[:space:]]+$' AND length("sourceUrl") <= 2000)),
  ADD CONSTRAINT "DataCenterSource_license_class_check" CHECK (
    ("licenseClass" IS DISTINCT FROM 'JENAN_OWNED' OR "ownership" = 'PLATFORM_OWNED')
    AND ("licenseClass" IS DISTINCT FROM 'RESTRICTED' OR NOT "allowExport")
  );
